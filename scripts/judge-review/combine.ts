// Builds the one GitHub review a judge round posts (#83). Judges write findings files; the
// builder's script (scripts/post-judge-review.ts) feeds them here once every judge is done.
// Pure: no I/O, so every decision is unit-tested.

export interface Finding {
  path: string
  line: number
  body: string
}
export interface Reply {
  commentId: number
  body: string
  resolve: boolean
}
export interface Counts {
  blockers: number
  shouldFix: number
  nits: number
  preExisting: number
}
export interface JudgeFile {
  judge: string
  phase: 'plan' | 'code'
  round: number
  commit: string
  verdict: 'APPROVE' | 'CHANGES'
  counts: Counts
  summary: string
  comments: Finding[]
  replies: Reply[]
}
export interface ReviewComment {
  path: string
  line: number
  side: 'RIGHT'
  body: string
}
export interface Combined {
  problems: string[]
  review: { commit_id: string; event: 'COMMENT'; body: string; comments: ReviewComment[] }
  replies: Reply[]
}
export interface Posted {
  reviewUrl: string
  repliesDone: number[]
}

export const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v)
}

export function parseJudgeFile(fileName: string, raw: string): JudgeFile {
  const fail = (what: string): never => {
    throw new Error(`${fileName}: ${what}`)
  }
  let data: unknown
  try {
    data = JSON.parse(raw)
  } catch {
    return fail('not valid JSON')
  }
  if (!isRecord(data)) return fail('not a JSON object')

  const str = (v: unknown, field: string): string =>
    typeof v === 'string' && v !== '' ? v : fail(`${field} must be a non-empty string`)
  const int = (v: unknown, field: string, min: number, max = Infinity): number =>
    typeof v === 'number' && Number.isInteger(v) && v >= min && v <= max
      ? v
      : fail(`${field} must be a whole number from ${min}${max === Infinity ? '' : ` to ${max}`}`)
  const list = (v: unknown, field: string): unknown[] =>
    Array.isArray(v) ? v : fail(`${field} must be an array`)
  const rec = (v: unknown, field: string): Record<string, unknown> =>
    isRecord(v) ? v : fail(`${field} must be an object`)

  const phase =
    data.phase === 'plan' || data.phase === 'code' ? data.phase : fail('phase must be plan or code')
  const verdict =
    data.verdict === 'APPROVE' || data.verdict === 'CHANGES'
      ? data.verdict
      : fail('verdict must be APPROVE or CHANGES')
  const counts = rec(data.counts, 'counts')
  const comments = list(data.comments, 'comments').map((c, i) => {
    const r = rec(c, `comments[${i}]`)
    return {
      path: str(r.path, `comments[${i}].path`),
      line: int(r.line, `comments[${i}].line`, 1),
      body: str(r.body, `comments[${i}].body`),
    }
  })
  const replies = list(data.replies, 'replies').map((c, i) => {
    const r = rec(c, `replies[${i}]`)
    return {
      commentId: int(r.commentId, `replies[${i}].commentId`, 1),
      body: str(r.body, `replies[${i}].body`),
      resolve:
        typeof r.resolve === 'boolean'
          ? r.resolve
          : fail(`replies[${i}].resolve must be true or false`),
    }
  })

  return {
    judge: str(data.judge, 'judge'),
    phase,
    round: int(data.round, 'round', 1, 5),
    commit: str(data.commit, 'commit'),
    verdict,
    counts: {
      blockers: int(counts.blockers, 'counts.blockers', 0),
      shouldFix: int(counts.shouldFix, 'counts.shouldFix', 0),
      nits: int(counts.nits, 'counts.nits', 0),
      preExisting: int(counts.preExisting, 'counts.preExisting', 0),
    },
    summary: str(data.summary, 'summary'),
    comments,
    replies,
  }
}

/** New-side lines GitHub accepts a RIGHT-side review comment on, per file of a unified diff. */
export function commentableLines(diff: string): Map<string, Set<number>> {
  const result = new Map<string, Set<number>>()
  let lines: Set<number> | null = null
  let next = 0
  // Lines still to come in the current hunk, from its @@ header. Inside a hunk, a line like
  // '+++ bold' is content, not a file header.
  let oldLeft = 0
  let newLeft = 0
  for (const text of diff.split('\n')) {
    if (oldLeft > 0 || newLeft > 0) {
      if (text.startsWith('-')) oldLeft -= 1
      else if (text.startsWith('+')) {
        lines?.add(next)
        next += 1
        newLeft -= 1
      } else if (text.startsWith(' ')) {
        lines?.add(next)
        next += 1
        oldLeft -= 1
        newLeft -= 1
      }
      continue // '\ No newline at end of file' counts for neither side
    }
    if (text.startsWith('diff --git ')) {
      lines = null
    } else if (text.startsWith('+++ ')) {
      const target = text.slice(4)
      lines = target.startsWith('b/') ? new Set<number>() : null // '/dev/null': deleted file
      if (lines) result.set(target.slice(2), lines)
    } else if (text.startsWith('@@ ')) {
      const m = /^@@ -\d+(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/.exec(text)
      next = Number(m?.[2] ?? 0)
      oldLeft = Number(m?.[1] ?? 1)
      newLeft = Number(m?.[3] ?? 1)
    }
  }
  for (const [path, set] of result) if (set.size === 0) result.delete(path)
  return result
}

function header(f: JudgeFile): string {
  const round = f.phase === 'plan' ? 'Plan round' : 'Round'
  const c = f.counts
  return [
    `[Judge: ${f.judge}] ${round} ${f.round} — ${f.verdict}`,
    `Blockers ${c.blockers} · Should-fix ${c.shouldFix} · Nits ${c.nits} · Pre-existing ${c.preExisting}`,
    f.summary,
  ].join('\n')
}

function anchor(finding: Finding, diff: Map<string, Set<number>>): ReviewComment {
  const own = diff.get(finding.path)
  if (own?.has(finding.line)) {
    return { path: finding.path, line: finding.line, side: 'RIGHT', body: finding.body + FOOTER }
  }
  const path = own ? finding.path : [...diff.keys()].sort()[0]
  const set = path === undefined ? undefined : diff.get(path)
  if (path === undefined || !set) throw new Error('the PR diff has no line to comment on')
  return {
    path,
    line: Math.min(...set),
    side: 'RIGHT',
    body: `Off the diff: \`${finding.path}:${finding.line}\`\n${finding.body}${FOOTER}`,
  }
}

export function combine(
  files: JudgeFile[],
  opts: { panel: string[]; headSha: string; diff: Map<string, Set<number>> },
): Combined {
  const problems: string[] = []
  const byJudge = new Map<string, JudgeFile>()
  for (const f of files) {
    if (!opts.panel.includes(f.judge))
      problems.push(`${f.judge}: not on the panel (${opts.panel.join(', ')})`)
    else if (byJudge.has(f.judge)) problems.push(`${f.judge}: more than one findings file`)
    else byJudge.set(f.judge, f)
  }
  for (const judge of opts.panel)
    if (!byJudge.has(judge)) problems.push(`${judge}: no findings file`)

  const ordered = opts.panel.flatMap((j) => byJudge.get(j) ?? [])
  for (const field of ['phase', 'round'] as const) {
    if (new Set(ordered.map((f) => f[field])).size > 1)
      problems.push(
        `files disagree on ${field}: ${ordered.map((f) => `${f.judge} ${f[field]}`).join(', ')}`,
      )
  }
  for (const f of ordered) {
    if (f.commit !== opts.headSha)
      problems.push(`${f.judge} reviewed ${f.commit}, PR head is ${opts.headSha}`)
    const expected = f.counts.blockers + f.counts.shouldFix > 0 ? 'CHANGES' : 'APPROVE'
    if (f.verdict !== expected)
      problems.push(`${f.judge}: verdict ${f.verdict} but counts say ${expected}`)
  }

  const comments: ReviewComment[] = []
  if (problems.length === 0) {
    try {
      for (const f of ordered) for (const c of f.comments) comments.push(anchor(c, opts.diff))
    } catch (e) {
      problems.push(e instanceof Error ? e.message : String(e))
    }
  }

  return {
    problems,
    review: {
      commit_id: opts.headSha,
      event: 'COMMENT',
      body: ordered.map(header).join('\n\n') + FOOTER,
      comments,
    },
    replies: ordered.flatMap((f) => f.replies.map((r) => ({ ...r, body: r.body + FOOTER }))),
  }
}

/** What is still to send, given the CLI's posted.json from an earlier run (null: none). */
export function pendingSteps(
  posted: Posted | null,
  replies: Reply[],
): { postReview: boolean; replies: Reply[] } {
  const done = new Set(posted?.repliesDone ?? [])
  return { postReview: posted === null, replies: replies.filter((r) => !done.has(r.commentId)) }
}
