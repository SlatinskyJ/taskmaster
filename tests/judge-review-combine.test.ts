import { describe, expect, it } from 'vitest'
import {
  combine,
  commentableLines,
  parseJudgeFile,
  pendingSteps,
  type JudgeFile,
} from '../scripts/judge-review/combine.ts'

const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
const SHA = 'a'.repeat(40)
const OTHER_SHA = 'b'.repeat(40)
const PANEL = ['Rules', 'Architecture', 'Tests']

const DIFF = [
  'diff --git a/a.ts b/a.ts',
  'index 1111111..2222222 100644',
  '--- a/a.ts',
  '+++ b/a.ts',
  '@@ -1,3 +1,4 @@',
  ' one',
  '+two',
  ' three',
  ' four',
  '@@ -10,2 +11,2 @@',
  '-old',
  '+new',
  ' keep',
  '\\ No newline at end of file',
  'diff --git a/old.ts b/new.ts',
  'similarity index 90%',
  'rename from old.ts',
  'rename to new.ts',
  '--- a/old.ts',
  '+++ b/new.ts',
  '@@ -5,1 +5,2 @@',
  ' x',
  '+y',
  'diff --git a/gone.ts b/gone.ts',
  'deleted file mode 100644',
  '--- a/gone.ts',
  '+++ /dev/null',
  '@@ -1,2 +0,0 @@',
  '-a',
  '-b',
  '',
].join('\n')

function judgeFile(judge: string, over: Partial<JudgeFile> = {}): JudgeFile {
  return {
    judge,
    phase: 'plan',
    round: 2,
    commit: SHA,
    verdict: 'APPROVE',
    counts: { blockers: 0, shouldFix: 0, nits: 0, preExisting: 0 },
    summary: `${judge} summary.`,
    comments: [],
    replies: [],
    ...over,
  }
}

function raw(over: Record<string, unknown> = {}): string {
  return JSON.stringify({ ...judgeFile('Rules'), ...over })
}

const diff = commentableLines(DIFF)
const run = (files: JudgeFile[]) => combine(files, { panel: PANEL, headSha: SHA, diff })
const all = () => PANEL.map((j) => judgeFile(j))

describe('parseJudgeFile', () => {
  it('accepts a valid file', () => {
    expect(parseJudgeFile('rules.json', raw())).toEqual(judgeFile('Rules'))
  })

  it.each([
    ['missing commit', raw({ commit: undefined })],
    ['round 0', raw({ round: 0 })],
    ['round 6', raw({ round: 6 })],
    ['bad verdict', raw({ verdict: 'OK' })],
    ['comment line not a number', raw({ comments: [{ path: 'a.ts', line: 'x', body: 'b' }] })],
    ['missing counts.nits', raw({ counts: { blockers: 0, shouldFix: 0, preExisting: 0 } })],
    [
      'counts.blockers a string',
      raw({ counts: { blockers: '1', shouldFix: 0, nits: 0, preExisting: 0 } }),
    ],
    ['reply without resolve', raw({ replies: [{ commentId: 1, body: 'Fixed' }] })],
    [
      'reply resolve not boolean',
      raw({ replies: [{ commentId: 1, body: 'Fixed', resolve: 'yes' }] }),
    ],
    ['invalid JSON', '{ not json'],
  ])('rejects %s, naming the file', (_name, text) => {
    expect(() => parseJudgeFile('rules.json', text)).toThrow(/rules\.json/)
  })
})

describe('commentableLines', () => {
  it('collects new-side added and context lines per file', () => {
    expect(diff).toEqual(
      new Map([
        ['a.ts', new Set([1, 2, 3, 4, 11, 12])],
        ['new.ts', new Set([5, 6])],
      ]),
    )
  })
})

describe('commentableLines edge cases', () => {
  it('reads an added line starting with ++ as content, not a file header', () => {
    const d = [
      'diff --git a/m.md b/m.md',
      '--- a/m.md',
      '+++ b/m.md',
      '@@ -1,1 +1,3 @@',
      ' a',
      '+++ bold',
      '+c',
      '',
    ].join('\n')
    expect(commentableLines(d)).toEqual(new Map([['m.md', new Set([1, 2, 3])]]))
  })

  it('reads a removed line starting with -- as content', () => {
    const d = [
      'diff --git a/m.md b/m.md',
      '--- a/m.md',
      '+++ b/m.md',
      '@@ -1,2 +1,1 @@',
      '--- rule',
      ' a',
      '',
    ].join('\n')
    expect(commentableLines(d)).toEqual(new Map([['m.md', new Set([1])]]))
  })
})

describe('combine', () => {
  it('builds one body with every judge in panel order', () => {
    const files = [judgeFile('Tests'), judgeFile('Rules'), judgeFile('Architecture')]
    const { problems, review } = run(files)
    expect(problems).toEqual([])
    expect(review.event).toBe('COMMENT')
    expect(review.commit_id).toBe(SHA)
    expect(review.body).toBe(
      [
        '[Judge: Rules] Plan round 2 — APPROVE',
        'Blockers 0 · Should-fix 0 · Nits 0 · Pre-existing 0',
        'Rules summary.',
        '',
        '[Judge: Architecture] Plan round 2 — APPROVE',
        'Blockers 0 · Should-fix 0 · Nits 0 · Pre-existing 0',
        'Architecture summary.',
        '',
        '[Judge: Tests] Plan round 2 — APPROVE',
        'Blockers 0 · Should-fix 0 · Nits 0 · Pre-existing 0',
        'Tests summary.',
      ].join('\n') + FOOTER,
    )
  })

  it('uses the code-phase header in code rounds', () => {
    const files = PANEL.map((j) => judgeFile(j, { phase: 'code', round: 3 }))
    expect(run(files).review.body.split('\n')[0]).toBe('[Judge: Rules] Round 3 — APPROVE')
  })

  it('missing panel judge is a problem', () => {
    expect(run([judgeFile('Rules'), judgeFile('Architecture')]).problems).toEqual([
      'Tests: no findings file',
    ])
  })

  it('commit mismatch is a problem', () => {
    const files = [
      judgeFile('Rules', { commit: OTHER_SHA }),
      judgeFile('Architecture'),
      judgeFile('Tests'),
    ]
    const { problems } = run(files)
    expect(problems).toHaveLength(1)
    expect(problems[0]).toContain('Rules')
    expect(problems[0]).toContain(OTHER_SHA)
    expect(problems[0]).toContain(SHA)
  })

  it.each([
    ['judge not on the panel', [...all(), judgeFile('UX')]],
    ['duplicate judge', [...all(), judgeFile('Tests')]],
    [
      'round mismatch',
      [judgeFile('Rules', { round: 1 }), judgeFile('Architecture'), judgeFile('Tests')],
    ],
    [
      'phase mismatch',
      [judgeFile('Rules', { phase: 'code' }), judgeFile('Architecture'), judgeFile('Tests')],
    ],
    [
      'CHANGES with no blocker or should-fix',
      [judgeFile('Rules', { verdict: 'CHANGES' }), judgeFile('Architecture'), judgeFile('Tests')],
    ],
    [
      'APPROVE with a should-fix',
      [
        judgeFile('Rules', { counts: { blockers: 0, shouldFix: 1, nits: 0, preExisting: 0 } }),
        judgeFile('Architecture'),
        judgeFile('Tests'),
      ],
    ],
  ])('%s is one problem', (_name, files) => {
    expect(run(files).problems).toHaveLength(1)
  })

  it('off-diff comment is re-anchored', () => {
    const files = [
      judgeFile('Rules', {
        comments: [
          { path: 'a.ts', line: 2, body: 'on the diff' },
          { path: 'a.ts', line: 999, body: 'far away' },
          { path: 'untouched.ts', line: 7, body: 'not in the diff' },
          { path: 'gone.ts', line: 1, body: 'deleted file' },
          { path: 'new.ts', line: 1, body: 'renamed file, off its hunk' },
        ],
      }),
      judgeFile('Architecture'),
      judgeFile('Tests'),
    ]
    const { problems, review } = run(files)
    expect(problems).toEqual([])
    expect(review.comments).toEqual([
      { path: 'a.ts', line: 2, side: 'RIGHT', body: 'on the diff' + FOOTER },
      { path: 'a.ts', line: 1, side: 'RIGHT', body: 'Off the diff: `a.ts:999`\nfar away' + FOOTER },
      {
        path: 'a.ts',
        line: 1,
        side: 'RIGHT',
        body: 'Off the diff: `untouched.ts:7`\nnot in the diff' + FOOTER,
      },
      {
        path: 'a.ts',
        line: 1,
        side: 'RIGHT',
        body: 'Off the diff: `gone.ts:1`\ndeleted file' + FOOTER,
      },
      {
        path: 'new.ts',
        line: 5,
        side: 'RIGHT',
        body: 'Off the diff: `new.ts:1`\nrenamed file, off its hunk' + FOOTER,
      },
    ])
  })

  it('is a problem when the diff has no line to comment on', () => {
    const files = [
      judgeFile('Rules', { comments: [{ path: 'a.ts', line: 1, body: 'x' }] }),
      judgeFile('Architecture'),
      judgeFile('Tests'),
    ]
    const { problems, review } = combine(files, { panel: PANEL, headSha: SHA, diff: new Map() })
    expect(problems).toEqual(['the PR diff has no line to comment on'])
    expect(review.comments).toEqual([])
  })

  it('replies are passed through', () => {
    const files = [
      judgeFile('Rules', {
        replies: [
          { commentId: 11, body: 'Fixed in abc', resolve: true },
          { commentId: 12, body: 'Still open: x', resolve: false },
        ],
      }),
      judgeFile('Architecture'),
      judgeFile('Tests'),
    ]
    expect(run(files).replies).toEqual([
      { commentId: 11, body: 'Fixed in abc' + FOOTER, resolve: true },
      { commentId: 12, body: 'Still open: x' + FOOTER, resolve: false },
    ])
  })
})

describe('pendingSteps', () => {
  const replies = [
    { commentId: 11, body: 'a', resolve: true },
    { commentId: 12, body: 'b', resolve: false },
  ]

  it('posts everything when nothing was posted yet', () => {
    expect(pendingSteps(null, replies)).toEqual({ postReview: true, replies })
  })

  it('skips the review and the replies already sent', () => {
    expect(pendingSteps({ reviewUrl: 'https://x', repliesDone: [11] }, replies)).toEqual({
      postReview: false,
      replies: [replies[1]],
    })
  })
})
